const yamlString = (s: string) => JSON.stringify(s)

/** The issue form. Its service options must match incident-kit.yml, so it is generated from it. */
export function issueForm(config: Config): string {
  const t = strings(config.lang)
  const th = config.lang === 'th'
  const levels = ([1, 2, 3, 4] as const).map((l) => `SEV${l} - ${t.severity[l].name}: ${t.severity[l].hint}`)
  return `# Generated by \`npx incident-kit init\` from incident-kit.yml. Run it again after you change the services.
name: ${th ? 'แจ้งเหตุขัดข้อง' : 'Declare an incident'}
description: ${th ? 'เริ่มกระบวนการรับมือเหตุขัดข้อง ผู้ควบคุมเหตุการณ์จะถูกมอบหมายให้อัตโนมัติ' : 'Start the incident process. The on-call commander is assigned automatically.'}
title: "${th ? '[เหตุขัดข้อง] ' : '[Incident] '}"
labels: [${config.label}]
body:
  - type: dropdown
    id: severity
    attributes:
      label: ${th ? 'ระดับความรุนแรง' : 'Severity'}
      options:
${levels.map((l) => `        - ${yamlString(l)}`).join('\n')}
    validations:
      required: true
  - type: dropdown
    id: services
    attributes:
      label: ${th ? 'บริการที่ได้รับผลกระทบ' : 'Affected services'}
      multiple: true
      options:
${config.services.map((s) => `        - ${yamlString(s.name)}`).join('\n')}
  - type: input
    id: public-title
    attributes:
      label: ${th ? 'หัวข้อบนหน้าสถานะ' : 'Public title'}
      description: ${th ? 'ข้อความที่ลูกค้าจะเห็น ถ้าเว้นว่างจะใช้ชื่อ issue' : 'What customers see on the status page. Leave empty to use the issue title.'}
  - type: textarea
    id: summary
    attributes:
      label: ${th ? 'เกิดอะไรขึ้น' : 'What is happening?'}
      description: ${th ? 'สิ่งที่รู้ตอนนี้ ข้อความนี้เป็นข้อมูลภายใน' : 'What you know so far. This stays internal.'}
    validations:
      required: true
  - type: input
    id: impact-start
    attributes:
      label: ${th ? 'ผลกระทบเริ่มเมื่อไหร่' : 'When did the impact start?'}
      description: ${th ? 'เช่น 2026-10-03 14:05 ตามเวลา' : 'For example 2026-10-03 14:05, in'} ${config.timezone}${th ? '' : ' time'}
`
}

